import type { LonLat } from '../types';
import { DEG, M_PER_DEG } from './mars';
import type { TerrainGrid } from './grid';

/**
 * SIMULATED terrain generator.
 *
 * This is NOT Jezero topography. It is a deterministic synthetic surface (crater-like bowl, noise, one
 * scarp with a gap) used only so the route engine can run end-to-end when no real DEM has been
 * supplied. Every UI surface that touches it is labelled SIMULATED. Replace it with a real DEM via the
 * pipeline in /pipeline and public/data/dem/.
 */

export const SIM_AOI = { west: 77.2, south: 18.1, east: 77.9, north: 18.7 } as const;
export const SIM_CELL_M = 100;

function hash2(ix: number, iy: number, seed: number): number {
  let h = Math.imul(ix, 374761393) + Math.imul(iy, 668265263) + Math.imul(seed, 1442695041);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967295;
}

function smooth(t: number): number {
  return t * t * (3 - 2 * t);
}

function valueNoise(x: number, y: number, seed: number): number {
  const ix = Math.floor(x);
  const iy = Math.floor(y);
  const fx = smooth(x - ix);
  const fy = smooth(y - iy);
  const a = hash2(ix, iy, seed);
  const b = hash2(ix + 1, iy, seed);
  const c = hash2(ix, iy + 1, seed);
  const d = hash2(ix + 1, iy + 1, seed);
  return a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy;
}

function fbm(x: number, y: number, seed: number, octaves = 4): number {
  let amp = 0.5;
  let f = 1;
  let sum = 0;
  for (let o = 0; o < octaves; o++) {
    sum += amp * (valueNoise(x * f, y * f, seed + o * 17) - 0.5) * 2;
    amp *= 0.5;
    f *= 2;
  }
  return sum;
}

function smoothstep(a: number, b: number, x: number): number {
  const t = Math.min(1, Math.max(0, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
}

export function simulatedElevation(xM: number, yM: number, seed = 2026): number {
  const cx = -3000;
  const cy = 2000;
  const r = Math.hypot(xM - cx, yM - cy);
  const bowl = -400 * (1 - smoothstep(8000, 10500, r)) + 120 * Math.exp(-(((r - 10500) / 700) ** 2));
  const broad = fbm(xM / 3000, yM / 3000, seed) * 70;
  const fine = fbm(xM / 700, yM / 700, seed + 101) * 18;
  const gap = 1 - 0.92 * Math.exp(-(((yM - 500) / 900) ** 2));
  const scarp = 95 * gap * smoothstep(-80, 80, xM - 4000 + 600 * Math.sin(yM / 2500));
  return bowl + broad + fine + scarp;
}

export function generateSimulatedTerrain(seed = 2026): TerrainGrid {
  const { west, south, east, north } = SIM_AOI;
  const midLat = (south + north) / 2;
  const dLat = SIM_CELL_M / M_PER_DEG;
  const dLon = dLat / Math.cos(midLat * DEG);
  const cols = Math.ceil((east - west) / dLon);
  const rows = Math.ceil((north - south) / dLat);
  const origin: LonLat = { lon: (west + east) / 2, lat: midLat };
  const elev = new Float32Array(cols * rows);
  for (let r = 0; r < rows; r++) {
    const lat = north - (r + 0.5) * dLat;
    const y = (lat - origin.lat) * M_PER_DEG;
    for (let c = 0; c < cols; c++) {
      const lon = west + (c + 0.5) * dLon;
      const x = (lon - origin.lon) * M_PER_DEG * Math.cos(origin.lat * DEG);
      elev[r * cols + c] = simulatedElevation(x, y, seed);
    }
  }
  return {
    id: 'astra-sim-terrain',
    source: 'simulated',
    dataClass: 'SIMULATED',
    label: 'SIMULATED demonstration terrain (not Jezero topography)',
    west,
    south,
    east: west + cols * dLon,
    north,
    cols,
    rows,
    dLon,
    dLat,
    elev,
    resolutionM: SIM_CELL_M,
    provenance:
      'Procedurally generated by PROJECT ASTRA (src/domain/simTerrain.ts). Heights are relative, synthetic metres.',
    limitations: [
      'Not derived from any NASA or USGS measurement.',
      'Slopes, elevation changes and route metrics on this surface are demonstrations of the algorithm only.',
      'Do not interpret computed routes as traversable on real Jezero terrain.',
    ],
  };
}
